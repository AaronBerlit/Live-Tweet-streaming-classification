"""`make train-all`: NB vs LR (C10) x all three emoji strategies (PRD §5.3).

Each combination is trained and evaluated through the real entrypoints
(`trainer.train`, `trainer.evaluate`), which write real metrics documents.
This script then reads those documents back from MongoDB and writes
`docs/experiments.md`. It computes no score itself and has no fallback: a
combination with no evaluation is reported as missing, not filled in.

The table is built from the latest stored evaluation of *every* combination,
not only the ones run in this invocation, so re-running one failed
combination (`--models lr --emoji keep`) fills its row without erasing the
others.

A note that belongs in the report, not just here: Sentiment140 ships as
`training.1600000.processed.noemoticon.csv` in ISO-8859-1, an encoding that
cannot represent emoji. Near-identical results across the three strategies
are therefore the *expected* finding, and the generated file cites the
measured emoji share so the reader can see why.
"""

from __future__ import annotations

import argparse
import subprocess
import sys
from datetime import datetime, timezone

from pymongo import DESCENDING, MongoClient

from pipeline.config import COLL_METRICS, DB_NAME, EMOJI_STRATEGIES, MODEL_NAMES, REPO_ROOT, settings

OUTPUT = REPO_ROOT / "docs" / "experiments.md"


def run(module: str, *arguments: str) -> bool:
    command = [sys.executable, "-m", module, *arguments]
    print(f"\n$ {' '.join(command[2:])}", flush=True)
    result = subprocess.run(command, cwd=str(REPO_ROOT), capture_output=True, text=True)
    if result.returncode != 0:
        # Surface the real failure instead of a bare "missing" row.
        tail = (result.stderr or result.stdout).strip().splitlines()[-15:]
        print(f"  FAILED (exit {result.returncode}):", flush=True)
        for line in tail:
            print(f"    {line}", flush=True)
    return result.returncode == 0


def tag(key: str, rows: int) -> str:
    """The notes value that identifies one experiment's metrics document."""
    return f"experiment {key} ({rows:,} rows)"


def macro_f1(document: dict) -> float:
    scores = list(document["f1"].values())
    return sum(scores) / len(scores) if scores else 0.0


def emoji_share() -> str:
    """The corpus's measured emoji share, from the generated profile."""
    profile = REPO_ROOT / "docs" / "dataset_profile.md"
    if not profile.exists():
        return "unknown (docs/dataset_profile.md not generated yet)"
    for line in profile.read_text(encoding="utf-8").splitlines():
        if line.startswith("| contains emoji"):
            return line.split("|")[2].strip()
    return "unknown"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--rows", type=int, default=200_000)
    parser.add_argument("--models", nargs="+", default=["nb", "lr"], choices=sorted(MODEL_NAMES))
    parser.add_argument("--emoji", nargs="+", default=list(EMOJI_STRATEGIES), choices=EMOJI_STRATEGIES)
    parser.add_argument("--report-only", action="store_true",
                        help="regenerate docs/experiments.md from stored results")
    args = parser.parse_args()

    client = MongoClient(settings.mongo_uri, serverSelectionTimeoutMS=10_000, tz_aware=True)
    metrics = client[DB_NAME][COLL_METRICS]

    failed_now: list[str] = []
    if not args.report_only:
        for model in args.models:
            for strategy in args.emoji:
                key = f"{model}_{strategy}"
                ok = run("trainer.train", "--model", model, "--emoji", strategy,
                         "--rows", str(args.rows), "--suffix", f"_{strategy}")
                ok = ok and run("trainer.evaluate", "--model", key, "--notes", tag(key, args.rows))
                if not ok:
                    failed_now.append(key)

    results = [
        {
            "model": model,
            "emoji": strategy,
            "doc": metrics.find_one(
                {"notes": tag(f"{model}_{strategy}", args.rows)},
                sort=[("trained_at", DESCENDING)],
            ),
        }
        for model in ("nb", "lr")
        for strategy in EMOJI_STRATEGIES
    ]

    baseline = {
        r["model"]: macro_f1(r["doc"]) for r in results if r["emoji"] == "strip" and r["doc"]
    }

    lines = [
        "# Experiments: model and emoji strategy",
        "",
        f"*Generated by `scripts/run_experiments.py` at "
        f"{datetime.now(timezone.utc):%Y-%m-%d %H:%M UTC}. Every figure below is "
        f"read back from a `metrics` document in MongoDB. Do not edit by hand.*",
        "",
        f"Training subset: {args.rows:,} rows, seeded random sample. Features: "
        f"HashingTF(65,536) + IDF, identical for both models (C10). Evaluated on the "
        f"full held-out test split.",
        "",
        "| model | emoji strategy | accuracy | macro F1 | Δ macro F1 vs strip | fit time |",
        "|---|---|---|---|---|---|",
    ]
    for r in results:
        name = MODEL_NAMES[r["model"]]
        if not r["doc"]:
            lines.append(f"| {name} | {r['emoji']} | not evaluated | — | — | — |")
            continue
        f1 = macro_f1(r["doc"])
        base = baseline.get(r["model"])
        delta = f"{(f1 - base) * 100:+.2f} pts" if base is not None else "—"
        lines.append(
            f"| {name} | {r['emoji']} | {r['doc']['accuracy']:.4f} | {f1:.4f} | "
            f"{delta} | {r['doc']['train_duration_sec']:.0f}s |"
        )

    nb, lr = baseline.get("nb"), baseline.get("lr")
    lines += ["", "## NB vs LR (C10)", ""]
    if nb is not None and lr is not None:
        lines.append(
            f"On identical features, logistic regression's macro F1 is "
            f"{(lr - nb) * 100:+.2f} points relative to naive Bayes "
            f"({lr:.4f} vs {nb:.4f})."
        )
    else:
        lines.append("Both models have not yet been evaluated with the `strip` strategy.")

    lines += [
        "",
        "## Reading the emoji result",
        "",
        f"Measured share of records containing emoji: **{emoji_share()}** "
        f"(from `docs/dataset_profile.md`).",
        "",
        "Sentiment140 is distributed as `training.1600000.processed.noemoticon.csv`: "
        "emoticons were removed upstream, and the file's ISO-8859-1 encoding cannot "
        "represent emoji at all. If the deltas above are zero, that is the finding: "
        "the emoji question cannot be settled on this corpus, and answering it would "
        "need a dataset that retains emoji.",
        "",
    ]
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"\nwrote {OUTPUT.relative_to(REPO_ROOT)}")

    missing = [f"{r['model']}_{r['emoji']}" for r in results if not r["doc"]]
    if failed_now or missing:
        print(f"incomplete: failed now {failed_now or 'none'}; missing {missing or 'none'}",
              file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
