"""C2/C3: generate docs/dataset_profile.md from the corpus itself.

Everything in the generated file is computed. There are no illustrative
numbers in it, which is the whole point -- the report cites this file, and the
file is regenerated by `make ingest`.

Contents required by PRD §5.1: schema, row count, file size, per-column null
and empty rates, label distribution (this is what evidences C3), text length
percentiles, share of records containing URLs / mentions / hashtags / emoji /
`RT ` prefixes, and ten raw sampled records.
"""

from __future__ import annotations

import argparse
import sys
from datetime import datetime, timezone
from pathlib import Path

from pyspark.sql import DataFrame, functions as F

from ingest.download import CSV_NAME, RAW_DIR
from ingest.load_raw import RAW_SCHEMA, SOURCE_ENCODING, add_labels
from pipeline import preprocess
from pipeline.config import REPO_ROOT
from pipeline.emoji_lexicon import EMOJI_RANGES

OUTPUT = REPO_ROOT / "docs" / "dataset_profile.md"

# Imported from the cleaner, never redefined here. With its own copies, this
# profile would report a "share containing emoji" or "share of retweets" that
# differed from what preprocessing actually strips -- two numbers describing
# the same corpus and quietly disagreeing, both cited in the report.
URL_RE = preprocess.URL_RE
MENTION_RE = preprocess.MENTION_RE
HASHTAG_RE = r"#\w+"
RETWEET_RE = preprocess.RETWEET_RE
EMOJI_RE = EMOJI_RANGES

PERCENTILES = [0.01, 0.25, 0.5, 0.75, 0.95, 0.99]


def _fraction(df: DataFrame, condition) -> float:
    """Share of rows satisfying a condition, as a fraction of the total."""
    return df.select(F.avg(F.when(condition, 1.0).otherwise(0.0))).first()[0] or 0.0


def _table(headers: list[str], rows: list[list[str]]) -> str:
    out = ["| " + " | ".join(headers) + " |",
           "|" + "|".join("---" for _ in headers) + "|"]
    out.extend("| " + " | ".join(row) + " |" for row in rows)
    return "\n".join(out)


def build_profile(df: DataFrame, csv_path: Path) -> str:
    total = df.count()
    size_mb = csv_path.stat().st_size / 1024 / 1024

    # --- per-column null / empty rates ---
    null_rows = []
    for field in RAW_SCHEMA.fields:
        col = F.col(field.name)
        nulls = _fraction(df, col.isNull())
        empties = (
            _fraction(df, F.trim(col) == "")
            if isinstance(field.dataType, type(RAW_SCHEMA["text"].dataType))
            else 0.0
        )
        null_rows.append(
            [
                f"`{field.name}`",
                field.dataType.simpleString(),
                f"{nulls * 100:.3f}%",
                f"{empties * 100:.3f}%",
            ]
        )

    # --- label distribution (C3) ---
    labels = (
        df.groupBy("target", "label")
        .count()
        .orderBy("target")
        .collect()
    )
    label_rows = [
        [str(r["target"]), r["label"] or "UNMAPPED", f"{r['count']:,}",
         f"{r['count'] / total * 100:.2f}%"]
        for r in labels
    ]
    present_targets = sorted(r["target"] for r in labels)

    # --- text length ---
    lengths = df.select(F.length("text").alias("len"))
    quantiles = lengths.approxQuantile("len", PERCENTILES, 0.001)
    stats = lengths.select(
        F.min("len").alias("min"), F.max("len").alias("max"), F.avg("len").alias("mean")
    ).first()

    # --- token classes (Variety) ---
    variety_rows = []
    for name, condition in [
        ("contains a URL", F.col("text").rlike(URL_RE)),
        ("contains an @mention", F.col("text").rlike(MENTION_RE)),
        ("contains a #hashtag", F.col("text").rlike(HASHTAG_RE)),
        ("contains emoji", F.col("text").rlike(EMOJI_RE)),
        ("is a retweet (RT prefix)", F.col("text").rlike(RETWEET_RE)),
    ]:
        share = _fraction(df, condition)
        variety_rows.append([name, f"{share * 100:.2f}%", f"{int(share * total):,}"])

    samples = df.select("target", "date", "user", "text").limit(10).collect()

    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    neutral_note = (
        "Only **0 (negative)** and **4 (positive)** appear. There is no neutral "
        "(2) label anywhere in the corpus, so a three-class model cannot be "
        "trained from this dataset alone -- neutral is not free. This is the "
        "finding behind claim C3, and it drives the `neutral_strategy` contract "
        "in the metrics document."
        if present_targets == [0, 4]
        else f"Targets present in this file: {present_targets}. "
        "The report's C3 claim must match this, not the documented ideal."
    )

    return f"""# Dataset profile — Sentiment140

*Generated by `ingest/profile_dataset.py` at {generated}. Do not edit by hand;
run `make ingest` to regenerate.*

Source file: `{csv_path.name}`
Size on disk: **{size_mb:,.1f} MB**
Rows: **{total:,}**
Encoding: `{SOURCE_ENCODING}` (the corpus is not UTF-8; reading it as UTF-8
corrupts every non-ASCII character and would invalidate the emoji experiments)

## Schema (C2)

The corpus ships with no header row. These six columns are declared explicitly
in `ingest/load_raw.py` rather than inferred.

{_table(["Column", "Type", "Null rate", "Empty rate"], null_rows)}

`date` is stored as a string in the source (e.g. `Mon Apr 06 22:19:45 PDT
2009`) and parsed to a timestamp on load. The three-letter zone is stripped
before parsing, so timestamps are treated as wall-clock UTC.

## Label distribution (C3)

{_table(["target", "label", "count", "share"], label_rows)}

{neutral_note}

## Text length

{_table(
    ["statistic", "characters"],
    [["min", f"{stats['min']}"], ["mean", f"{stats['mean']:.1f}"], ["max", f"{stats['max']}"]]
    + [[f"p{int(p * 100)}", f"{int(q)}"] for p, q in zip(PERCENTILES, quantiles)],
)}

## Variety — what is actually in the text

This is the evidence behind the third V. The records are not clean prose: they
carry URLs, mentions, hashtags, emoji and retweet prefixes, and the metadata
columns are inconsistently populated.

{_table(["feature", "share of records", "approx. count"], variety_rows)}

## Ten raw records, unmodified

```
{chr(10).join(f"{r['target']}  {r['date']}  {r['user']}  {r['text']!r}" for r in samples)}
```
"""


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--csv", type=Path, default=RAW_DIR / CSV_NAME)
    parser.add_argument("--rows", type=int, default=None, help="cap rows for a fast run")
    args = parser.parse_args()

    if not args.csv.exists():
        print(f"corpus not found at {args.csv}", file=sys.stderr)
        print("run: python -m ingest.download", file=sys.stderr)
        return 1

    from scripts.spark_session import build

    spark = build("profile-dataset", mongo=False)

    df = (
        spark.read.option("header", "false")
        .option("encoding", SOURCE_ENCODING)
        .option("escape", '"')
        .schema(RAW_SCHEMA)
        .csv(args.csv.resolve().as_uri())  # explicit file://: fs.defaultFS may be HDFS
    )
    if args.rows:
        df = df.limit(args.rows)
    df = add_labels(df).cache()

    print("profiling the corpus (several passes over the full file)...")
    profile = build_profile(df, args.csv)

    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(profile, encoding="utf-8")
    spark.stop()

    print(f"\nC2/C3 satisfied: wrote {OUTPUT.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
